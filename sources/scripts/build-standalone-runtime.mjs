import fs from "node:fs";
import path from "node:path";
import * as esbuild from "esbuild";

const rootDir = path.resolve(import.meta.dirname, "..");
const entryFile = path.join(rootDir, "src", "engine", "standaloneRuntimeEntry.ts");
const outDir = path.join(rootDir, "src", "engine", "generated");
const outTsFile = path.join(outDir, "standaloneRuntimeBundle.ts");

fs.mkdirSync(outDir, { recursive: true });

const result = await esbuild.build({
  entryPoints: [entryFile],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  write: false,
  logLevel: "silent",
});

const bundledJs = result.outputFiles?.[0]?.text ?? "";
if (!bundledJs) {
  throw new Error("Failed to bundle standaloneRuntimeEntry.ts");
}

// Escape closing script tags safely for inline <script> injection
const safePayload = bundledJs.replace(/<\/script/gi, "<\\/script");
const tsModule = `// Auto-generated by scripts/build-standalone-runtime.mjs — do not edit manually\nexport const STANDALONE_RUNTIME_BUNDLE: string = ${JSON.stringify(safePayload)};\n`;

fs.writeFileSync(outTsFile, tsModule, "utf8");
console.log(`Built standaloneRuntimeBundle.ts (${Math.round(safePayload.length / 1024)} KB)`);
